def calculate_shiny_odds(
    method: str = "wild",
    radar_chain: int = 0,
    diglett_bonus: bool = False,
    masuda: bool = False,
    shiny_charm: bool = False,
) -> Dict[str, Any]:
    """
    Calculates exact Pokémon Brilliant Diamond shiny odds based on hunting method and modifiers.
    Note: In BDSP, the Shiny Charm only affects breeding (Eggs), NOT wild/radar/static encounters!
    """
    chain_clamped = max(0, min(40, radar_chain))

    if method == "poke_radar":
        denom_single = POKE_RADAR_DENOMINATORS.get(chain_clamped, 4096)
        prob_single = 1.0 / denom_single
        # When continuing a Poke Radar chain, 4 grass patches shake simultaneously
        prob_four_patches = 1.0 - ((1.0 - prob_single) ** 4)
        effective_denom_4 = round(1.0 / prob_four_patches) if prob_four_patches > 0 else denom_single
        return {
            "method": "poke_radar",
            "radar_chain": chain_clamped,
            "single_patch_odds": f"1 / {denom_single:,}",
            "single_patch_denom": denom_single,
            "single_patch_percent": round(prob_single * 100, 4),
            "four_patch_odds": f"1 / {effective_denom_4:,}",
            "four_patch_denom": effective_denom_4,
            "four_patch_percent": round(prob_four_patches * 100, 3),
            "active_probability": prob_four_patches,
            "active_odds_label": f"1 / {effective_denom_4:,} (4 patches) • 1 / {denom_single:,} per patch",
            "bdsp_note": "At chain 40+, each of the 4 shaking patches has a 1/99 chance of sparkling (~3.98% per reset)!",
        }

    if method == "masuda_egg":
        rolls = 1
        if masuda:
            rolls += 5  # Masuda adds +5 rolls (6/4096 = 1/683)
        if shiny_charm:
            rolls += 2  # Shiny Charm works on Eggs in BDSP (+2 rolls -> 8/4096 = 1/512)
        prob = rolls / 4096.0
        denom = round(4096 / rolls)
        return {
            "method": "masuda_egg",
            "rolls": rolls,
            "single_patch_odds": f"1 / {denom:,}",
            "single_patch_denom": denom,
            "single_patch_percent": round(prob * 100, 4),
            "active_probability": prob,
            "active_odds_label": f"1 / {denom:,} ({rolls}/4096 rolls)",
            "bdsp_note": "In BDSP, the Shiny Charm properly applies its +2 extra shiny rolls to Eggs (1/512 with Masuda + Charm)!",
        }

    if method == "underground" or diglett_bonus:
        rolls = 2 if diglett_bonus else 1
        prob = rolls / 4096.0
        denom = round(4096 / rolls)
        return {
            "method": "underground",
            "rolls": rolls,
            "single_patch_odds": f"1 / {denom:,}",
            "single_patch_denom": denom,
            "single_patch_percent": round(prob * 100, 4),
            "active_probability": prob,
            "active_odds_label": f"1 / {denom:,}",
            "bdsp_note": "Collecting 40/40 Diglett sparkles in the Grand Underground doubles shiny odds to 2/4096 (1/2,048) for 4 minutes.",
        }

    # Standard Wild / Static / Fishing / Surfing
    rolls = 1
    prob = rolls / 4096.0
    denom = 4096
    return {
        "method": "wild",
        "rolls": rolls,
        "single_patch_odds": "1 / 4,096",
        "single_patch_denom": denom,
        "single_patch_percent": round(prob * 100, 4),
        "active_probability": prob,
        "active_odds_label": "1 / 4,096",
        "bdsp_note": (
            "Heads-up: Due to a quirk in Brilliant Diamond & Shining Pearl's code, the Shiny Charm only affects breeding Eggs—wild & static encounters remain 1/4,096 unless using the Poké Radar!"
            if shiny_charm
            else "Base Gen 8 shiny rate is 1/4,096 (0.0244%). Use the Poké Radar slider to see chain odds up to 1/99!"
        ),
    }
